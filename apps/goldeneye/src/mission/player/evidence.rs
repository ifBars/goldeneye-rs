//! Public diagnostics contain identities/counts/hashes, never source rig arrays.
use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub(crate) struct Evidence {
    pub state: &'static str,
    pub requested_character: u32,
    pub catalog_resource: u32,
    pub catalog_payload_bytes: u32,
    pub character_sheet: u32,
    pub character_group: u8,
    pub character_row_stride: u8,
    pub character_rows: usize,
    pub duplicate_character_rows: usize,
    pub selected_character: u32,
    pub selected_source_index: usize,
    pub selected_source_address: usize,
    pub native_default_fallback_used: bool,
    pub component_resource: u32,
    pub component_payload_bytes: u32,
    pub component_reference: u32,
    pub skin_resource: u32,
    pub skin_payload_bytes: u32,
    pub skin_reference: u32,
    pub skin_directory_index: usize,
    pub skin_hash: u32,
    pub skin_body_address: usize,
    pub retained_resources: usize,
    pub retained_payload_bytes: u64,
    pub bone_count: usize,
    pub root_count: usize,
    pub topology_sha256: String,
    pub constructor_state_sha256: String,
    pub camera_tag: u32,
    pub camera_tag_found: bool,
    pub camera_bone: Option<u16>,
    pub camera_parent_chain_length: usize,
    pub camera_parent_chain_sha256: Option<String>,
    pub skeleton_constructor_initialized: bool,
    pub animation_sampled: bool,
    pub player_physics_initialized: bool,
    pub camera_frame_ready: bool,
    pub mode_plan: Option<super::animation::Evidence>,
    pub initial_layers: Option<super::runtime::Evidence>,
    pub camera_bone_transform: Option<super::camera::Evidence>,
    pub scope: &'static str,
}
